<script setup lang="ts">
/** 人物详情页：头部信息（含内容类型徽标）+ 照片组 + 人脸注册 + 风格画像 + 素材瀑布流。
 *
 * 编排层：数据加载与业务逻辑在 composables/usePersonDetail 及人脸注册 composables，
 * 区块 UI 在 components/person/detail/ 子组件；本视图只做组装与事件接线。
 */

import { usePersonDetail } from '@/composables/usePersonDetail'
import { useRouter } from 'vue-router'
import { Message } from '@arco-design/web-vue'
import { getApiErrorMessage } from '@/utils/apiError'
import { usePageTitle } from '@/composables/usePageTitle'
import { computed, ref, watch } from 'vue'
import { bloggersApi, modelsApi } from '@/api/persons'
import ImageLightbox from '@/components/inspiration/ImageLightbox.vue'
import PersonFormModal from '@/components/person/PersonFormModal.vue'
import PersonDetailHeader from '@/components/person/detail/PersonDetailHeader.vue'
import PersonStyleProfile from '@/components/person/detail/PersonStyleProfile.vue'
import PersonPhotoSets from '@/components/person/detail/PersonPhotoSets.vue'
import PersonBloggerFaceRegister from '@/components/person/detail/PersonBloggerFaceRegister.vue'
import PersonModelFaceRegister from '@/components/person/detail/PersonModelFaceRegister.vue'
import PersonGroupCard from '@/components/person/detail/PersonGroupCard.vue'
import PersonItemsSection from '@/components/person/detail/PersonItemsSection.vue'
import PersonInsightsCard from '@/components/person/detail/PersonInsightsCard.vue'
import PersonSimilarCard from '@/components/person/detail/PersonSimilarCard.vue'
import PersonFaceCandidatesModal from '@/components/person/detail/PersonFaceCandidatesModal.vue'
import { usePersonDetailExtras } from '@/composables/usePersonDetailExtras'
import { useWorksDownload } from '@/composables/useWorksDownload'

const router = useRouter()

const {
  personId,
  kind,
  kindLabel,
  detail,
  loading,
  isProfileUrlSafe,
  items,
  total,
  page,
  pageSize,
  itemsLoading,
  lightboxOpen,
  lightboxPaths,
  photoSets,
  photoSetsLoading,
  photoLightboxOpen,
  photoLightboxPaths,
  showForm,
  backToList,
  handleDelete,
  goSearchByTag,
  openPhotoSet,
  handleDeletePhotoSet,
  goAddPhotos,
  setPage,
  loadDetail,
  viewMode,
  sort,
  filters,
  works,
  worksTotal,
  worksTotalItems,
  worksPage,
  worksSize,
  worksLoading,
  setViewMode,
  setWorksPage,
  setFilters,
  setSort,
  unbindMode,
  unbindSelectedIds,
  unbindSubmitting,
  clearingAll,
  isCurrentPageAllSelected,
  enterUnbindMode,
  exitUnbindMode,
  toggleUnbindSelect,
  toggleSelectCurrentPage,
  confirmUnbindSelected,
  unbindAll,
} = usePersonDetail()

// 浏览器标题：人物管理-<网名>（名字要等详情加载完才知道，加载中先显示「人物管理」）
const pageTitle = computed(() =>
  detail.value?.name ? `人物管理-${detail.value.name}` : '人物管理',
)
usePageTitle(pageTitle)

/** 详情页简介区域「AI 生成」入口：打开编辑弹窗并自动触发一次生成 */
const autoGenerateBio = ref(false)
function handleHeaderGenerateBio() {
  autoGenerateBio.value = true
  showForm.value = true
}
function onAutoGenerateDone() {
  autoGenerateBio.value = false
}

// ── 增强区（洞察 / 相似 / 人脸候选 / 资料补齐）──
const {
  insights,
  insightsLoading,
  similar,
  duplicates,
  similarLoading,
  enriching,
  faceCandidates,
  faceCandidatesLoading,
  faceCandidatesVisible,
  faceRegistering,
  hasFaceCandidates,
  loadInsightsAndSimilar,
  enrichProfile,
  openFaceCandidates,
  registerFaceFromIds,
} = usePersonDetailExtras(
  () => personId.value,
  () => kind.value,
  async () => {
    await loadDetail()
  },
)

/** 筛选下拉用的标签：直接取风格画像的高频标签，不为一个下拉多发一次请求 */
const tagOptions = computed(() =>
  (detail.value?.style_profile?.top_tags ?? []).map((t) => t.name).slice(0, 30),
)

/** 作品组灯箱：点某个作品时临时把该组素材路径交给灯箱（与「全屏浏览全部」互不干扰） */
const workPaths = ref<string[]>([])
function openWorkLightbox(paths: string[]) {
  workPaths.value = paths
  lightboxOpen.value = true
}
function closeLightbox() {
  lightboxOpen.value = false
  workPaths.value = []
}

/** 点质量构成某一段 → 直接按该质量筛选素材 */
function onFilterQuality(status: 'approved' | 'pending' | 'rejected') {
  void setFilters({ ...filters.value, quality_status: status })
}

/** 打开风格相近的博主（同种类详情页；列表页带 kind 参数，这里保持不变） */
function openPerson(id: number) {
  router.push({ path: `/persons/${id}`, query: { kind: kind.value } })
}

/** 疑似同名合并：建一个人物组（后端只做绑定，不改名不删数据）。
 *
 * 接口是「一对一」建组（``{blogger_id, target_blogger_id}``），所以从当前人物开始
 * 逐个把其它账号并进来——最后形成的组里包含全部账号。
 */
async function onMergeDuplicate(ids: number[], _name: string) {
  const others = ids.filter((id) => id !== personId.value)
  if (!others.length) return
  try {
    for (const other of others) {
      await bloggersApi.linkGroup({
        blogger_id: personId.value,
        target_blogger_id: other,
      })
    }
    Message.success(`已合并为同一人（${others.length + 1} 个账号）`)
    await loadDetail()
    await loadInsightsAndSimilar()
  } catch (e) {
    Message.error(getApiErrorMessage(e, '合并失败'))
  }
}

/** 人脸绑定变化（注册/注销）后退出多选模式、重置分页并刷新素材瀑布流与头部统计 */
async function onFaceChanged() {
  exitUnbindMode()
  page.value = 1
  await Promise.all([loadDetail()])
}

// ── 「下载所有作品」（仅穿搭博主：点名她的主页链接，让 f2 翻全量下载并入库）──
// 素材来自抖音「我的喜欢 / 我的收藏」时博主可能没有主页链接：composable 会先用素材里的
// 真实作品 ID 自动解析出作者主页，再提交下载（解析失败会给出后端原因）
const {
  loadStatus: loadF2Status,
  resolving: worksResolving,
  state: worksDownload,
  downloadAllWorks,
} = useWorksDownload(
  () => (kind.value === 'blogger' && detail.value ? detail.value : null),
  loadDetail,
)

// 进博主页时读一次 f2 状态（模特页没有这个入口，不为此多发请求）：
// 按钮的可用性既要看人物够不够格，也要看 f2 通道本身是否就绪
watch(
  kind,
  (value) => {
    if (value === 'blogger') void loadF2Status({ silent: true })
  },
  { immediate: true },
)

// 洞察/相似/人脸候选都属于「附属信息」：进页面并行拉，失败只少一块区域
watch(
  personId,
  () => {
    if (kind.value === 'blogger') void loadInsightsAndSimilar()
  },
  { immediate: true },
)
</script>

<template>
  <div class="person-detail-page">
    <a-spin :loading="loading">
      <template v-if="detail">
        <!-- 面包屑 -->
        <a-breadcrumb style="margin-bottom: 16px">
          <a-breadcrumb-item @click="backToList">人物管理</a-breadcrumb-item>
          <a-breadcrumb-item>{{ detail.name }}</a-breadcrumb-item>
        </a-breadcrumb>

        <!-- 头部信息卡 -->
        <PersonDetailHeader
          :detail="detail"
          :kind="kind"
          :kind-label="kindLabel"
          :profile-url-safe="isProfileUrlSafe"
          :works-download-disabled="worksDownload.disabled"
          :works-download-reason="worksDownload.reason"
          :works-download-needs-resolve="worksDownload.needsResolve"
          :works-download-resolving="worksResolving"
          @download-works="downloadAllWorks"
          @edit="showForm = true"
          @delete="handleDelete"
          @generate-bio="handleHeaderGenerateBio"
          @avatar-changed="loadDetail"
          :enriching="enriching"
          :has-face-candidates="hasFaceCandidates"
          @enrich="enrichProfile"
          @open-face-candidates="openFaceCandidates"
        />

        <!-- 人物组（方案 B）：同一现实人物跨平台账号（仅穿搭博主） -->
        <PersonGroupCard v-if="kind === 'blogger'" :person="detail" @changed="loadDetail" />

        <!-- 照片组（模特写真，仅职业模特展示；与穿搭素材分离） -->
        <PersonPhotoSets
          v-if="kind === 'model'"
          :photo-sets="photoSets"
          :loading="photoSetsLoading"
          @open="openPhotoSet"
          @delete="handleDeletePhotoSet"
          @add="goAddPhotos"
        />

        <!-- 人脸特征注册（模特：从照片组；博主：上传照片/素材选择） -->
        <PersonModelFaceRegister v-if="kind === 'model'" :person-id="personId" :api="modelsApi" />
        <PersonBloggerFaceRegister
          v-if="kind === 'blogger'"
          :person-id="personId"
          :api="bloggersApi"
          @changed="onFaceChanged"
        />

        <!-- 风格画像 -->
        <PersonStyleProfile :profile="detail.style_profile" @search-tag="goSearchByTag" />

        <!-- 素材区（作品/全部双视图 + 筛选 + 人脸注销多选） -->
        <PersonItemsSection
          :kind="kind"
          :items="items"
          :total="total"
          :page="page"
          :page-size="pageSize"
          :loading="itemsLoading"
          :filters="filters"
          :sort="sort"
          :view-mode="viewMode"
          :works="works"
          :works-total="worksTotal"
          :works-total-items="worksTotalItems"
          :works-page="worksPage"
          :works-page-size="worksSize"
          :works-loading="worksLoading"
          :tag-options="tagOptions"
          :unbind-mode="unbindMode"
          :unbind-selected-ids="unbindSelectedIds"
          :unbind-submitting="unbindSubmitting"
          :clearing-all="clearingAll"
          :is-current-page-all-selected="isCurrentPageAllSelected"
          @update:view-mode="setViewMode"
          @update:sort="setSort"
          @update:filters="setFilters"
          @page-change="setPage"
          @works-page-change="setWorksPage"
          @clear-filters="setFilters({})"
          @open-lightbox="lightboxOpen = true"
          @open-work="openWorkLightbox"
          @enter-unbind="enterUnbindMode"
          @exit-unbind="exitUnbindMode"
          @toggle-select="toggleUnbindSelect"
          @toggle-select-page="toggleSelectCurrentPage"
          @confirm-unbind="confirmUnbindSelected"
          @unbind-all="unbindAll"
        />

        <!-- 洞察（B3 活跃度 + B4 质量构成） -->
        <PersonInsightsCard
          :insights="insights"
          :loading="insightsLoading"
          @filter-quality="onFilterQuality"
        />

        <!-- 风格相近 / 疑似同名（B5，仅博主：模特只有 1 位，没有推荐意义） -->
        <PersonSimilarCard
          v-if="kind === 'blogger'"
          :similar="similar"
          :duplicates="duplicates"
          :loading="similarLoading"
          :current-id="personId"
          @open-person="openPerson"
          @merge-duplicate="onMergeDuplicate"
        />

        <!-- 全屏灯箱：浏览该人物图片素材（或某个作品组：workPaths 临时接管） -->
        <ImageLightbox
          :show="lightboxOpen"
          :image-paths="workPaths.length ? workPaths : lightboxPaths"
          :initial-index="0"
          @close="closeLightbox"
        />

        <!-- 全屏灯箱：浏览照片组照片 -->
        <ImageLightbox
          :show="photoLightboxOpen"
          :image-paths="photoLightboxPaths"
          :initial-index="0"
          @close="photoLightboxOpen = false"
        />
      </template>
    </a-spin>

    <!-- 人脸注册候选（A3：从已匹配素材 / 未匹配候选脸簇一键注册） -->
    <PersonFaceCandidatesModal
      :visible="faceCandidatesVisible"
      :loading="faceCandidatesLoading"
      :registering="faceRegistering"
      :candidates="faceCandidates"
      :person-name="detail?.name ?? ''"
      @update:visible="faceCandidatesVisible = $event"
      @register="registerFaceFromIds"
    />

    <!-- 编辑对话框 -->
    <PersonFormModal
      v-model:show="showForm"
      :kind="kind"
      :person="detail"
      :auto-generate-bio="autoGenerateBio"
      @auto-generate-done="onAutoGenerateDone"
      @saved="loadDetail()"
    />
  </div>
</template>

